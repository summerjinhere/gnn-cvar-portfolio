import numpy as np
import pandas as pd
from scipy.optimize import minimize

# 수익률 및 공분산행렬
returns = price.pct_change().dropna()
mean_returns = returns.mean() * 252
cov_matrix = returns.cov() * 252
tickers = mean_returns.index
rf = 0.04  # 연간 무위험 수익률

# 1. Sharpe Ratio 최대화 함수 정의
def negative_sharpe(weights):
    port_return = np.dot(weights, mean_returns)
    port_std = np.sqrt(np.dot(weights.T, np.dot(cov_matrix, weights)))
    sharpe = (port_return - rf) / port_std
    return -sharpe

# 2. Risk(Variance) 최소화 함수 정의
def portfolio_volatility(weights):
    return np.sqrt(np.dot(weights.T, np.dot(cov_matrix, weights)))

# 공통 제약조건 및 초기값
n = len(tickers)
constraints = ({'type': 'eq', 'fun': lambda x: np.sum(x) - 1})
bounds = tuple((0, 1) for _ in range(n))
init_guess = np.ones(n) / n

# 최적화 수행
opt_sharpe = minimize(negative_sharpe, init_guess, method='SLSQP', bounds=bounds, constraints=constraints)
opt_risk = minimize(portfolio_volatility, init_guess, method='SLSQP', bounds=bounds, constraints=constraints)

# 결과 저장
weights_sharpe = pd.Series(opt_sharpe.x, index=tickers)
weights_risk = pd.Series(opt_risk.x, index=tickers)

# 요약 출력
