import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import minimize

# 기본 데이터: 기대수익률, 공분산행렬, 종목 수
mu = mean_returns.values  # 기대수익률 벡터 (연율)
cov = cov_matrix.values   # 공분산 행렬 (연율)
tickers = mean_returns.index
n_assets = len(tickers)

# 경계 제약 조건
bounds = tuple((0, 1) for _ in range(n_assets))
constraints_sum = {'type': 'eq', 'fun': lambda w: np.sum(w) - 1}

# 목표 수익률 범위 설정 (선형 등간격)
target_returns = np.linspace(mu.min(), mu.max(), 100)
frontier_risks = []

for r_target in target_returns:
    constraints_return = {
        'type': 'eq',
        'fun': lambda w, mu=mu, r_target=r_target: np.dot(w, mu) - r_target
    }

    result = minimize(
        lambda w: np.dot(w.T, np.dot(cov, w)),  # 분산 최소화
        x0=np.ones(n_assets) / n_assets,
        bounds=bounds,
        constraints=[constraints_sum, constraints_return],
        method='SLSQP'
    )

    if result.success:
        risk = np.sqrt(np.dot(result.x.T, np.dot(cov, result.x)))
        frontier_risks.append(risk)
    else:
        frontier_risks.append(np.nan)

# 시각화
